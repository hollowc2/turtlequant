"""Public performance page for billybitcoin.cloud/turtlequant/ — stats and HTML.

The page is a static snapshot regenerated by cron (scripts/generate_performance_page.py).
It mirrors the ButterflyGuy page on the same site: server-rendered stats and tables,
chart data in a non-executable <script type="application/json"> block, and one inline
script whose bytes never change between runs. The site's CSP allows that script by
its sha256 hash, so regenerating the numbers must never touch _PAGE_SCRIPT.
"""

