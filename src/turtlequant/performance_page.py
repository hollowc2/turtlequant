def _longest_streak(pnls: list[float], winning: bool) -> int:
    best = run = 0
    for pnl in pnls:
        if (pnl > 0) if winning else (pnl < 0):
            run += 1
            best = max(best, run)
        else:
            run = 0
    return best


def daily_returns(
    trades: list[ClosedTrade], starting_nav: float, as_of: dt.datetime
) -> list[float]:
    """Realised daily returns on NAV, one per UTC calendar day.

    The window runs from the first trade's open (or close) to as_of, and days with
    no closes count as 0% — leaving them out would overstate Sharpe.
    """
    if not trades or starting_nav <= 0:
        return []
    first = min((t.opened_at or t.closed_at) for t in trades).date()
    last = max(as_of.astimezone(dt.UTC).date(), trades[-1].closed_at.date())
    pnl_by_day: dict[dt.date, float] = {}
    for trade in trades:
        day = trade.closed_at.astimezone(dt.UTC).date()
        pnl_by_day[day] = pnl_by_day.get(day, 0.0) + trade.pnl
    returns: list[float] = []
    equity = starting_nav
    day = first
    while day <= last:
        pnl = pnl_by_day.get(day, 0.0)
        returns.append(pnl / equity if equity > 0 else 0.0)
        equity += pnl
        day += dt.timedelta(days=1)
    return returns


def sharpe_ratio(returns: list[float]) -> float | None:
    if len(returns) < 2:
        return None
    mean = sum(returns) / len(returns)
    var = sum((r - mean) ** 2 for r in returns) / (len(returns) - 1)
    if var <= 0:
        return None
    return mean / math.sqrt(var) * math.sqrt(ANNUALIZATION_DAYS)


def sortino_ratio(returns: list[float]) -> float | None:
    if len(returns) < 2:
        return None
    mean = sum(returns) / len(returns)
    downside = math.sqrt(sum(min(r, 0.0) ** 2 for r in returns) / len(returns))
    if downside <= 0:
        return None
    return mean / downside * math.sqrt(ANNUALIZATION_DAYS)


def equity_series(trades: list[ClosedTrade], starting_nav: float) -> list[dict[str, float]]:
    """NAV, running peak and drawdown after each trade."""
    nav = peak = starting_nav
    points: list[dict[str, float]] = []
    for trade in trades:
        nav += trade.pnl
        peak = max(peak, nav)
        dd_usd = peak - nav
        points.append({
            "nav": nav,
            "peak": peak,
            "dd_usd": dd_usd,
            "dd_pct": dd_usd / peak * 100.0 if peak > 0 else 0.0,
        })
    return points


def compute_stats(
    trades: list[ClosedTrade], starting_nav: float, as_of: dt.datetime
) -> Stats:
    pnls = [t.pnl for t in trades]
    wins = [p for p in pnls if p > 0]
    losses = [p for p in pnls if p < 0]
    total = sum(pnls)
    gross_loss = -sum(losses)
    series = equity_series(trades, starting_nav)
    returns = daily_returns(trades, starting_nav, as_of)
    holds = [h for t in trades if (h := t.hold_hours) is not None]
    edges = [e for t in trades if (e := t.edge_at_entry) is not None]
    avg_win = sum(wins) / len(wins) if wins else None
    avg_loss = sum(losses) / len(losses) if losses else None
    worst_point = max(series, key=lambda p: p["dd_usd"], default=None)
    return Stats(
        starting_nav=starting_nav,
        ending_nav=starting_nav + total,
        total_pnl=total,
        return_pct=total / starting_nav * 100.0 if starting_nav > 0 else 0.0,
        trade_count=len(pnls),
        wins=len(wins),
        losses=len(losses),
        win_rate=len(wins) / len(pnls) * 100.0 if pnls else 0.0,
        profit_factor=sum(wins) / gross_loss if gross_loss > 0 else None,
        expectancy=total / len(pnls) if pnls else 0.0,
        avg_win=avg_win,
        avg_loss=avg_loss,
        payoff_ratio=avg_win / -avg_loss if avg_win is not None and avg_loss else None,
        best=max(pnls, default=0.0),
        worst=min(pnls, default=0.0),
        max_drawdown_usd=worst_point["dd_usd"] if worst_point else 0.0,
        max_drawdown_pct=max((p["dd_pct"] for p in series), default=0.0),
        current_drawdown_pct=series[-1]["dd_pct"] if series else 0.0,
        sharpe=sharpe_ratio(returns),
        sortino=sortino_ratio(returns),
        avg_hold_hours=sum(holds) / len(holds) if holds else None,
        max_win_streak=_longest_streak(pnls, winning=True),
        max_loss_streak=_longest_streak(pnls, winning=False),
        avg_edge_at_entry=sum(edges) / len(edges) if edges else None,
        volume_usd=sum(t.size_usd or 0.0 for t in trades),
        days_tracked=len(returns),
    )


def chart_payload(trades: list[ClosedTrade], starting_nav: float) -> dict[str, Any]:
    rows: list[dict[str, Any]] = []
    for index, (trade, point) in enumerate(zip(trades, equity_series(trades, starting_nav), strict=True)):
        rows.append({
            "index": index + 1,
            "date": trade.closed_at.strftime("%Y-%m-%d"),
            "closed": trade.closed_at.strftime("%Y-%m-%d %H:%M UTC"),
            "asset": trade.asset,
            "question": trade.question[:110],
            "entry": trade.entry_price,
            "exit": trade.exit_price,
            "size": trade.size_usd,
            "hold_h": trade.hold_hours,
            "reason": trade.exit_reason,
            "pnl": trade.pnl,
            "ret": trade.return_pct,
            "nav": point["nav"],
            "peak": point["peak"],
            "dd_usd": point["dd_usd"],
            "dd_pct": point["dd_pct"],
        })
    return {"startNav": starting_nav, "trades": rows}


