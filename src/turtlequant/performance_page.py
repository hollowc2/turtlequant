_DASH = "—"


def _usd(value: float | None, *, signed: bool = False, dp: int = 2) -> str:
    if value is None:
        return _DASH
    sign = ("+" if value > 0 else "-" if value < 0 else "") if signed else ("-" if value < 0 else "")
    return f"{sign}${abs(value):,.{dp}f}"


def _pct(value: float | None, *, signed: bool = False, dp: int = 1) -> str:
    if value is None:
        return _DASH
    return f"{value:+.{dp}f}%" if signed and round(value, dp) else f"{value:.{dp}f}%"


def _ratio(value: float | None) -> str:
    return _DASH if value is None else f"{value:.2f}"


def _cents(price: float | None) -> str:
    return _DASH if price is None else f"{price * 100:.1f}¢"


def _hold(hours: float | None) -> str:
    if hours is None:
        return _DASH
    if hours < 48:
        return f"{hours:.1f}h"
    return f"{hours / 24:.1f}d"


def _date(value: dt.datetime | None, fmt: str = "%Y-%m-%d") -> str:
    return _DASH if value is None else value.astimezone(dt.UTC).strftime(fmt)


def _strike(value: float | None) -> str:
    return _DASH if value is None else f"${value:,.0f}"


def _tone(value: float | None) -> str:
    if value is None or value == 0:
        return ""
    return "pos" if value > 0 else "neg"


def _label(text: str) -> str:
    return html.escape(text.replace("_", " "))


def _json_data_block(payload: dict[str, Any]) -> str:
    """Serialise payload for a <script type="application/json"> block.

    Script content is raw text, so the only hazard is a "</script" sequence in the
    data (market questions are third-party text). JSON \\uXXXX escapes for < > &
    remove it while round-tripping through JSON.parse() unchanged.
    """
    encoded = json.dumps(payload, allow_nan=False)
    return encoded.replace("&", "\\u0026").replace("<", "\\u003c").replace(">", "\\u003e")


def _tile(label: str, value: str, *, tone: str = "", sub: str = "") -> str:
    sub_html = f"<div class='sub'>{sub}</div>" if sub else ""
    return (
        f"<div class='stat'><div class='label'>{html.escape(label)}</div>"
        f"<div class='value {tone}'>{value}</div>{sub_html}</div>"
    )


def _cohort_tiles(trades: list[ClosedTrade], key: str) -> str:
    groups: dict[str, list[ClosedTrade]] = {}
    for trade in trades:
        groups.setdefault(getattr(trade, key), []).append(trade)
    tiles = []
    for name, group in sorted(groups.items(), key=lambda item: -len(item[1])):
        pnl = sum(t.pnl for t in group)
        win_rate = sum(1 for t in group if t.pnl > 0) / len(group) * 100.0
        tiles.append(
            _tile(
                name.replace("_", " "),
                f"{len(group)} trade{'' if len(group) == 1 else 's'}",
                sub=f"<span class='{_tone(pnl)}'>{_usd(pnl, signed=True)}</span> · {win_rate:.0f}% win",
            )
        )
    return "".join(tiles) or "<div class='muted-note'>No closed trades yet.</div>"


def _trade_rows(trades: list[ClosedTrade]) -> str:
    rows = []
    for number, trade in reversed(list(enumerate(trades, start=1))):
        outcome = "win" if trade.pnl > 0 else "loss" if trade.pnl < 0 else "flat"
        question = html.escape(trade.question)
        rows.append(
            f"<tr data-outcome='{outcome}'>"
            f"<td>{number}</td>"
            f"<td class='l'>{_date(trade.opened_at, '%Y-%m-%d %H:%M')}</td>"
            f"<td class='l'>{_date(trade.closed_at, '%Y-%m-%d %H:%M')}</td>"
            f"<td>{_hold(trade.hold_hours)}</td>"
            f"<td class='l'>{html.escape(trade.asset)}</td>"
            f"<td class='l market' title='{question}'>{question}</td>"
            f"<td class='l'>{_label(trade.option_type)}</td>"
            f"<td class='l'>{html.escape(trade.outcome)}</td>"
            f"<td>{_strike(trade.strike)}</td>"
            f"<td>{_date(trade.expiry)}</td>"
            f"<td>{_pct(trade.model_prob_at_entry * 100 if trade.model_prob_at_entry is not None else None)}</td>"
            f"<td>{_pct(trade.edge_at_entry * 100 if trade.edge_at_entry is not None else None, signed=True)}</td>"
            f"<td>{_cents(trade.entry_price)}</td>"
            f"<td>{_cents(trade.exit_price)}</td>"
            f"<td>{_usd(trade.size_usd)}</td>"
            f"<td class='l'>{_label(trade.exit_reason)}</td>"
            f"<td class='{_tone(trade.return_pct)}'>{_pct(trade.return_pct, signed=True)}</td>"
            f"<td class='{_tone(trade.pnl)}'>{_usd(trade.pnl, signed=True)}</td>"
            "</tr>"
        )
    if not rows:
        return "<tr><td colspan='18' class='empty-cell'>No closed trades yet.</td></tr>"
    return "".join(rows)


def _open_rows(positions: list[OpenPosition]) -> str:
    rows = []
    for pos in positions:
        question = html.escape(pos.question)
        status = "awaiting redemption" if pos.status == "pending_redemption" else pos.status
        rows.append(
            "<tr>"
            f"<td class='l'>{_date(pos.opened_at, '%Y-%m-%d %H:%M')}</td>"
            f"<td class='l'>{html.escape(pos.asset)}</td>"
            f"<td class='l market' title='{question}'>{question}</td>"
            f"<td class='l'>{_label(pos.option_type)}</td>"
            f"<td class='l'>{html.escape(pos.outcome)}</td>"
            f"<td>{_strike(pos.strike)}</td>"
            f"<td>{_date(pos.expiry)}</td>"
            f"<td>{_pct(pos.edge_at_entry * 100, signed=True)}</td>"
            f"<td>{_cents(pos.entry_price)}</td>"
            f"<td>{_cents(pos.mark_price)}</td>"
            f"<td>{_usd(pos.size_usd)}</td>"
            f"<td class='l'>{html.escape(status)}</td>"
            f"<td class='{_tone(pos.unrealized_pnl)}'>{_usd(pos.unrealized_pnl, signed=True)}</td>"
            "</tr>"
        )
    if not rows:
        return "<tr><td colspan='13' class='empty-cell'>No open positions.</td></tr>"
    return "".join(rows)


# ---------------------------------------------------------------------------
# Chart descriptions (the only thing a screen reader gets for each canvas, so they
# are computed from the same data the charts draw rather than written by hand)
# ---------------------------------------------------------------------------


def equity_description(trades: list[ClosedTrade], stats: Stats) -> str:
    if not trades:
        return f"Line chart of realized NAV. No closed trades yet; NAV is {_usd(stats.starting_nav)}."
    return (
        f"Line chart of realized NAV across {stats.trade_count} closed trades, "
        f"{_date(trades[0].closed_at)} to {_date(trades[-1].closed_at)}. It starts at "
        f"{_usd(stats.starting_nav)} and ends at {_usd(stats.ending_nav)}, "
        f"a return of {_pct(stats.return_pct, signed=True)}. Every trade is listed in the trade log below."
    )


def drawdown_description(stats: Stats) -> str:
    opening = "Line chart of how far realized NAV sits below its running peak, in percent."
    if not stats.trade_count:
        return f"{opening} No closed trades yet."
    return (
        f"{opening} The deepest drawdown is {_pct(stats.max_drawdown_pct)} "
        f"({_usd(stats.max_drawdown_usd)}); the latest reading is {_pct(stats.current_drawdown_pct)}."
    )


def distribution_description(stats: Stats) -> str:
    opening = "Bar chart counting closed trades by percent return on position size."
    if not stats.trade_count:
        return f"{opening} No closed trades yet."
    return (
        f"{opening} {stats.wins} trades won and {stats.losses} lost; the best returned "
        f"{_usd(stats.best, signed=True)} and the worst {_usd(stats.worst, signed=True)}."
    )


