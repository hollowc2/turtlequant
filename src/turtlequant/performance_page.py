# Crypto markets trade every calendar day, so daily returns annualise over 365.
ANNUALIZATION_DAYS = 365
MODE_LABELS = {
    "shadow": ("Shadow Trading", "Simulated fills against live Polymarket order books"),
    "paper": ("Paper Trading", "Simulated fills against live Polymarket order books"),
    "live": ("Live Trading", "Real orders on the Polymarket CLOB"),
}


@dataclass(frozen=True)
class ClosedTrade:
    market_id: str
    question: str
    asset: str
    option_type: str
    strike: float | None
    expiry: dt.datetime | None
    opened_at: dt.datetime | None
    closed_at: dt.datetime
    entry_price: float | None
    exit_price: float | None
    size_usd: float | None
    edge_at_entry: float | None
    model_prob_at_entry: float | None
    exit_reason: str
    pnl: float
    outcome: str = "YES"  # token held; prices are that token's

    @property
    def return_pct(self) -> float | None:
        return self.pnl / self.size_usd * 100.0 if self.size_usd else None

    @property
    def hold_hours(self) -> float | None:
        if self.opened_at is None:
            return None
        return (self.closed_at - self.opened_at).total_seconds() / 3600.0


@dataclass(frozen=True)
class OpenPosition:
    market_id: str
    question: str
    asset: str
    option_type: str
    strike: float
    expiry: dt.datetime | None
    opened_at: dt.datetime | None
    entry_price: float
    mark_price: float
    size_usd: float
    tokens: float
    edge_at_entry: float
    status: str
    outcome: str = "YES"

    @property
    def unrealized_pnl(self) -> float:
        return (self.mark_price - self.entry_price) * self.tokens


@dataclass(frozen=True)
class Stats:
    starting_nav: float
    ending_nav: float
    total_pnl: float
    return_pct: float
    trade_count: int
    wins: int
    losses: int
    win_rate: float
    profit_factor: float | None  # None when there are no losing trades
    expectancy: float
    avg_win: float | None
    avg_loss: float | None
    payoff_ratio: float | None
    best: float
    worst: float
    max_drawdown_usd: float
    max_drawdown_pct: float
    current_drawdown_pct: float
    sharpe: float | None
    sortino: float | None
    avg_hold_hours: float | None
    max_win_streak: int
    max_loss_streak: int
    avg_edge_at_entry: float | None
    volume_usd: float
    days_tracked: int


