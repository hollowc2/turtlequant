def parse_ts(value: object) -> dt.datetime | None:
    if not isinstance(value, str) or not value:
        return None
    try:
        parsed = dt.datetime.fromisoformat(value)
    except ValueError:
        return None
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=dt.UTC)


def _opt_float(value: object) -> float | None:
    try:
        result = float(value)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return None
    return result if math.isfinite(result) else None


def build_closed_trades(events: list[dict[str, Any]]) -> list[ClosedTrade]:
    """Pair each close with its open (FIFO per market) into round-trip trades.

    partial_close P&L is carried into the round trip it belongs to, so a trade's
    P&L is everything realised between its open and its final close.
    """
    opens: dict[str, list[dict[str, Any]]] = {}
    partial_pnl: dict[str, float] = {}
    trades: list[ClosedTrade] = []
    for event in events:
        kind = event.get("event")
        market_id = str(event.get("market_id", ""))
        if kind == "open":
            opens.setdefault(market_id, []).append(event)
        elif kind == "partial_close":
            partial_pnl[market_id] = partial_pnl.get(market_id, 0.0) + (_opt_float(event.get("pnl")) or 0.0)
        elif kind == "close":
            closed_at = parse_ts(event.get("ts"))
            if closed_at is None:
                continue
            queue = opens.get(market_id)
            open_event = queue.pop(0) if queue else None
            earlier = partial_pnl.pop(market_id, None)
            if earlier is None:
                pnl = effective_close_pnl(open_event, event)
            else:
                pnl = earlier + (_opt_float(event.get("pnl")) or 0.0)
            opened = open_event or {}
            trades.append(
                ClosedTrade(
                    market_id=market_id,
                    question=str(opened.get("question") or event.get("question") or market_id),
                    asset=str(event.get("asset") or opened.get("asset") or "?").upper(),
                    option_type=str(opened.get("option_type") or "—"),
                    strike=_opt_float(event.get("strike", opened.get("strike"))),
                    expiry=parse_ts(opened.get("expiry")),
                    opened_at=parse_ts(opened.get("ts")),
                    closed_at=closed_at,
                    entry_price=_opt_float(opened.get("yes_price")),
                    exit_price=_opt_float(event.get("yes_price", event.get("exit_price"))),
                    size_usd=_opt_float(opened.get("size_usd")),
                    edge_at_entry=_opt_float(opened.get("edge")),
                    model_prob_at_entry=_opt_float(opened.get("model_prob")),
                    exit_reason=str(event.get("reason") or "—"),
                    pnl=pnl,
                    outcome=str(opened.get("outcome") or event.get("outcome") or "YES"),
                )
            )
    trades.sort(key=lambda t: t.closed_at)
    return trades


def open_positions_from_state(state: dict[str, Any]) -> list[OpenPosition]:
    """Open claims from the positions file, marked like PositionManager.marked_equity."""
    positions: list[OpenPosition] = []
    for raw in state.get("positions") or []:
        if not isinstance(raw, dict):
            continue
        entry = _opt_float(raw.get("entry_price")) or 0.0
        size = _opt_float(raw.get("size_usd")) or 0.0
        if entry <= 0 or size <= 0:
            continue
        status = str(raw.get("status") or "open")
        if status == "pending_redemption" and raw.get("resolution_price") is not None:
            mark = _opt_float(raw.get("resolution_price")) or 0.0
        else:
            mark = (
                _opt_float(raw.get("last_bid"))
                or _opt_float(raw.get("last_yes_price"))
                or entry
            )
        positions.append(
            OpenPosition(
                market_id=str(raw.get("market_id", "")),
                question=str(raw.get("question") or ""),
                asset=str(raw.get("asset") or "?").upper(),
                option_type=str(raw.get("option_type") or "—"),
                strike=_opt_float(raw.get("strike")) or 0.0,
                expiry=parse_ts(raw.get("expiry_iso")),
                opened_at=parse_ts(raw.get("opened_at")),
                entry_price=entry,
                mark_price=mark,
                size_usd=size,
                tokens=_opt_float(raw.get("token_size")) or size / entry,
                edge_at_entry=_opt_float(raw.get("edge_at_entry")) or 0.0,
                status=status,
                outcome=str(raw.get("outcome") or "YES"),
            )
        )
    positions.sort(key=lambda p: p.opened_at or dt.datetime.min.replace(tzinfo=dt.UTC))
    return positions


